export function updateTelemetry(state, player, ads, sway, motion, weapon, recoil, camera, input) {
  state.playerSpeed = player.speed;
  state.sprint = player.sprint.value;
  state.crouch = player.crouch.value;
  state.ads = ads.blend;
  state.sway.x = sway.position.value.x;
  state.sway.y = sway.position.value.y;
  state.sway.z = sway.position.value.z;
  state.motion.x = motion.position.value.x;
  state.motion.y = motion.position.value.y;
  state.motion.z = motion.position.value.z;
  state.final.x = weapon.finalPosition.x;
  state.final.y = weapon.finalPosition.y;
  state.final.z = weapon.finalPosition.z;
  state.recoil.pitch = recoil.pitch.value;
  state.recoil.yaw = recoil.yaw.value;
  state.recoil.roll = recoil.roll.value;
  state.recoil.punch = recoil.punch.value;
  state.recoil.shots = recoil.shots;
  state.camera.x = camera.position.x;
  state.camera.y = camera.position.y;
  state.camera.z = camera.position.z;
  state.camera.pitch = camera.rotation.x;
  state.camera.yaw = camera.rotation.y;
  state.camera.roll = camera.rotation.z;
  state.input.left = input.mouseHeld(0);
  state.input.right = input.mouseHeld(2);
  state.input.pointerButtons = input.pointerButtons;
  state.input.pointerSeen = input.pointerInputSeen;
  state.input.failed = input.pointerLockFailed;
  state.input.locked = input.pointerLocked;
}
